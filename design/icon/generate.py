#!/usr/bin/env python3
"""Generates the app icon from one set of parameters:
design/icon/ashidori.svg (source), design/icon/ashidori-rounded.svg (the same with
rounded corners, for the README) and
app/src/main/res/drawable/ic_launcher_fg.xml (adaptive-icon foreground and
monochrome layer). Shoe prints walk up-right to a place marker; the whole
mark is centred and scaled to fit the 66 dp safe-zone circle of a 108 dp icon.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

BG, FG, ACC = "#0B6E62", "#FFFFFF", "#FF9A4D"
ANGLE = 40            # walking direction, degrees clockwise from "up"
STEP, SIDE, FOOT = 17.0, 5.5, 0.85  # step length, lateral offset, print scale
START = (36.0, 76.0)  # first print, before centring
PIN_GAP = 13.0        # from the last print to the marker's tip, along the walk
SAFE_R = 33.0         # safe-zone radius

# One right shoe print pointing up (sole + heel); the left one is mirrored.
FOOT_D = ("M0.4,-12C4.8,-12 6,-7 5.6,-2.6C5.3,1.2 3.8,3.2 0.4,3.2C-3.2,3.2 -4.6,1 -4.6,-2.8"
          "C-4.6,-7.6 -3.6,-12 0.4,-12Z M-0.5,5.4h0.8a3.3,3.3 0,0 1,3.3 3.3a3.3,3.3 0,0 1,-3.3 3.3"
          "h-0.8a3.3,3.3 0,0 1,-3.3 -3.3a3.3,3.3 0,0 1,3.3 -3.3Z")
FOOT_PTS = [(x, y) for x in (-4.6, 5.6) for y in (-12, 12)]
# Marker with its tip at (0,0) and a hole (even-odd).
PIN_D = ("M0,-29.4C-6.6,-29.4 -11.4,-24.4 -11.4,-18.2C-11.4,-10.4 0,0 0,0C0,0 11.4,-10.4 11.4,-18.2"
         "C11.4,-24.4 6.6,-29.4 0,-29.4Z M0,-22.4a4.2,4.2 0,1 0,0 8.4a4.2,4.2 0,1 0,0 -8.4Z")
PIN_PTS = [(-11.4, -29.4), (11.4, -29.4), (-11.4, -18.2), (11.4, -18.2), (0, 0)]

a = math.radians(ANGLE)
d = (math.sin(a), -math.cos(a))          # forward
r = (math.cos(a), math.sin(a))           # to the walker's right
feet = []
for k in range(3):
    base = (START[0] + k * STEP * d[0], START[1] + k * STEP * d[1])
    sgn = 1 if k % 2 else -1               # left, right, left
    feet.append(((base[0] + sgn * SIDE * r[0], base[1] + sgn * SIDE * r[1]), sgn))
last = (START[0] + 2 * STEP * d[0], START[1] + 2 * STEP * d[1])
tip = (last[0] + PIN_GAP * d[0], last[1] + PIN_GAP * d[1] + 4)

def place_foot(p, sgn, pt):
    x, y = pt[0] * FOOT * (1 if sgn > 0 else -1), pt[1] * FOOT
    c, s = math.cos(a), math.sin(a)
    return (p[0] + x * c - y * s, p[1] + x * s + y * c)

pts = [place_foot(p, s, q) for p, s in feet for q in FOOT_PTS] + [(tip[0] + x, tip[1] + y) for x, y in PIN_PTS]
cx = (min(x for x, _ in pts) + max(x for x, _ in pts)) / 2
cy = (min(y for _, y in pts) + max(y for _, y in pts)) / 2
shift = (54 - cx, 54 - cy)
far = max(math.hypot(x - cx, y - cy) for x, y in pts)
scale = round(SAFE_R / far, 3)

def fx(v): return f"{v:.2f}".rstrip("0").rstrip(".")

# --- SVG ---
uses = "\n".join(
    f'      <use href="#foot" transform="translate({fx(p[0]+shift[0])} {fx(p[1]+shift[1])}) rotate({ANGLE}) scale({fx(FOOT*s)} {fx(FOOT)})"/>'
    for p, s in feet)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">
  <!-- Generated by design/icon/generate.py. Shoe prints walking to a place marker. -->
  <defs><path id="foot" d="{FOOT_D}"/></defs>
  <rect width="108" height="108" fill="{BG}"/>
  <g transform="translate(54 54) scale({scale}) translate(-54 -54)">
    <g fill="{FG}">
{uses}
    </g>
    <path fill="{ACC}" fill-rule="evenodd" transform="translate({fx(tip[0]+shift[0])} {fx(tip[1]+shift[1])})" d="{PIN_D}"/>
  </g>
</svg>
'''
open(os.path.join(HERE, "ashidori.svg"), "w").write(svg)
# The same with rounded corners, as launchers show it, for the README and other
# pages (the mark lies within the safe zone, so nothing is cut).
open(os.path.join(HERE, "ashidori-rounded.svg"), "w").write(
    svg.replace(f'<rect width="108" height="108" fill="{BG}"/>', f'<rect width="108" height="108" rx="24" fill="{BG}"/>'))

# --- VectorDrawable ---
groups = "\n".join(f'''        <group android:translateX="{fx(p[0]+shift[0])}" android:translateY="{fx(p[1]+shift[1])}" android:rotation="{ANGLE}" android:scaleX="{fx(FOOT*s)}" android:scaleY="{fx(FOOT)}">
            <path android:fillColor="#FF{FG[1:]}" android:pathData="{FOOT_D}" />
        </group>''' for p, s in feet)
vd = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/generate.py: launcher foreground and monochrome
     layer. Shoe prints walking to a place marker, fitted to the safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:pivotX="54" android:pivotY="54" android:scaleX="{scale}" android:scaleY="{scale}">
{groups}
        <group android:translateX="{fx(tip[0]+shift[0])}" android:translateY="{fx(tip[1]+shift[1])}">
            <path android:fillColor="#FF{ACC[1:]}" android:fillType="evenOdd" android:pathData="{PIN_D}" />
        </group>
    </group>
</vector>
'''
open(os.path.join(ROOT, "app/src/main/res/drawable/ic_launcher_fg.xml"), "w").write(vd)
print(f"scale {scale}, centre shift {shift[0]:.1f},{shift[1]:.1f}")
